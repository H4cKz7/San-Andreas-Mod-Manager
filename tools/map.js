#!/usr/bin/env node
/*
 * tools/map.js: writes renderer/MAP.md, a table of contents of the code base.
 * For every renderer/js file it lists the top-level functions and consts, so an AI (or you)
 * can see which file to open for a task without reading any of them.
 *
 *   node tools/map.js          (run it after adding / moving / renaming functions)
 *   node tools/map.js --check  (exit code 1 if MAP.md is out of date; useful in a pre-commit hook)
 */
'use strict';
const fs = require('fs'), path = require('path'), os = require('os'), cp = require('child_process');
const ROOT = path.resolve(__dirname, '..'), JS = path.join(ROOT, 'renderer', 'js'), CSS = path.join(ROOT, 'renderer', 'css');
const OUT = path.join(ROOT, 'renderer', 'MAP.md');

function loadAcorn() {
  try { return require('acorn'); } catch (e) {}
  const tmp = path.join(os.tmpdir(), 'samm-split-acorn'), p = path.join(tmp, 'node_modules', 'acorn');
  try { return require(p); } catch (e) {}
  fs.mkdirSync(tmp, { recursive: true });
  cp.execSync(`npm install --prefix "${tmp}" acorn --no-audit --no-fund --loglevel=error`, { stdio: 'inherit' });
  return require(p);
}
const acorn = loadAcorn();
const names = p => p.type === 'Identifier' ? [p.name] : p.type === 'ObjectPattern' ? p.properties.flatMap(x => names(x.value || x.argument)) : p.type === 'ArrayPattern' ? p.elements.filter(Boolean).flatMap(names) : p.type === 'AssignmentPattern' ? names(p.left) : p.type === 'RestElement' ? names(p.argument) : [];
const kb = f => (fs.statSync(f).size / 1024).toFixed(1) + ' KB';
const head = f => (fs.readFileSync(f, 'utf8').match(/^\/\*\s*SA Mod Manager - [^:]+:\s*(.*?)\s*(\(loaded[^)]*\))?\s*\*\//) || [])[1] || '';
const list = (d, ext) => fs.existsSync(d) ? fs.readdirSync(d).filter(f => f.endsWith(ext)).sort() : [];

let md = `# SA Mod Manager: code map (generated by tools/map.js, do not edit by hand)

Renderer code is split into **classic scripts** that share one global scope. They are loaded in the order of
the \`<script>\` tags in \`index.html\` (numeric prefix = load order). There is no import/export.
Main process: \`main.js\`. Node bridge for the page: \`fsshim.js\`.

To change something: find the file below, open **only that file**, edit, done.

## JavaScript (renderer/js)
`;
for (const f of list(JS, '.js')) {
  const full = path.join(JS, f), src = fs.readFileSync(full, 'utf8');
  let fn = [], vr = [];
  try {
    acorn.parse(src, { ecmaVersion: 'latest', sourceType: 'script' }).body.forEach(st => {
      if (st.type === 'FunctionDeclaration') fn.push(st.id.name + (st.async ? '*' : ''));
      else if (st.type === 'ClassDeclaration') fn.push(st.id.name);
      else if (st.type === 'VariableDeclaration') st.declarations.forEach(d => names(d.id).forEach(n => vr.push(n)));
    });
  } catch (e) { fn.push('(parse error: ' + e.message + ')'); }
  md += `\n### ${f}  (${kb(full)})\n${head(full)}\n`;
  if (fn.length) md += `- functions: ${fn.join(', ')}\n`;
  if (vr.length) md += `- top-level consts/vars: ${vr.join(', ')}\n`;
}
md += `\n(\`name*\` = async function)\n\n## CSS (renderer/css), loaded in this order, later files override earlier ones\n`;
for (const f of list(CSS, '.css')) md += `- **${f}** (${kb(path.join(CSS, f))}): ${head(path.join(CSS, f))}\n`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== md) { console.error('renderer/MAP.md is out of date. Run: node tools/map.js'); process.exit(1); }
  console.log('renderer/MAP.md is up to date'); process.exit(0);
}
fs.writeFileSync(OUT, md);
console.log('Wrote ' + path.relative(ROOT, OUT));
